export function getDefaultCourseIds(department: DepartmentId, grade: number): string[] {
  if (department === 'nursing') {
    if (grade >= 2) {
      return ['nur-201', 'nur-202', 'gen-101', 'gen-102'];
    }
    return ['nur-101', 'nur-102', 'nur-103', 'nur-104', 'gen-101', 'gen-102'];
  }
  if (department === 'cs') {
    return ['cs-101', 'cs-102', 'cs-103', 'gen-101', 'gen-102'];
  }
  if (department === 'business') {
    return ['biz-101', 'biz-102', 'gen-101', 'gen-102'];
  }
  return ['psy-101', 'psy-102', 'gen-101', 'gen-102'];
}

